import re


def _clean_text(text):
    """清理多余空白和重复标点。"""
    if not isinstance(text, str):
        return ""

    text = re.sub(r"\s+", " ", text).strip()
    text = re.sub(r"[，,]{2,}", "，", text)
    text = re.sub(r"[。.!！?？]{2,}", "。", text)
    return text.strip(" ，,。.!！?？")


