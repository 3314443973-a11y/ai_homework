def apply_summary_rules(text):
    """依次应用通用规则，归一化常见表达。"""
    for pattern, replacement in SUMMARY_RULES:
        text = re.sub(pattern, replacement, text)
    return text


def local_summarize(text):
    """本地兜底摘要：归一化常见表达，尽量保留原始信息。"""
    text = _clean_text(text)
    if not text:
        return ""

    text = apply_summary_rules(text)
    text = _clean_text(text)

    if not text:
        return ""

    # 暂不强行截断，避免丢失时间、影响和风险信息
    if not text.endswith(("。", "！", "？")):
        text += "。"

    return text


