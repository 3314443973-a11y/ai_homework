def clean_text(text):
    """清理明显的情绪表达，不保存情绪信息。"""
    if not isinstance(text, str):
        return ""

    text = text.strip()

    for phrase in EMOTION_PHRASES:
        text = text.replace(phrase, "")

    text = re.sub(r"\s+", "", text)
    text = re.sub(r"[，,。！？!?；;]+", "，", text)
    return text.strip("，")


